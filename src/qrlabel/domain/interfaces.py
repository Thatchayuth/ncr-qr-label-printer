"""Interfaces (structural Protocols) between layers.

Concrete classes do not need to inherit from these; they only need matching methods.
"""
from __future__ import annotations

from typing import Any, Protocol

from .models import DataProfile, LabelTemplate, PrintJob, PrintStatus, SendResult

Record = dict[str, Any]  # column name (UPPER CASE) -> value


class IDataSourceRepository(Protocol):
    def test_connection(self) -> str: ...
    def list_columns(self, source: str, schema: str = "dbo") -> list[tuple[str, str]]: ...
    def search(
        self, profile: DataProfile, criteria: dict[str, str], company: str,
        ranges: dict[str, tuple[Any, Any]] | None = None,
    ) -> list[Record]: ...


class IQueryProfileRepository(Protocol):
    def list_latest(self) -> list[DataProfile]: ...
    def get(self, profile_id: str, version: int | None = None) -> DataProfile | None: ...
    def save(self, profile: DataProfile) -> DataProfile: ...


class ILabelTemplateRepository(Protocol):
    def list_latest(self) -> list[LabelTemplate]: ...
    def get(self, template_id: str, version: int | None = None) -> LabelTemplate | None: ...
    def save(self, template: LabelTemplate) -> LabelTemplate: ...


class IQrPayloadBuilder(Protocol):
    def build(self, record: Record, profile: DataProfile) -> Any: ...


class ILabelRenderer(Protocol):
    def render_job(self, template: LabelTemplate, labels: list[tuple[dict[str, str], str | None]], copies: int) -> tuple[bytes, list[str]]: ...


class IPrinterAdapter(Protocol):
    kind: str
    target: str

    def test_connection(self) -> str: ...
    def send(self, data: bytes, job_name: str) -> SendResult: ...


class IPrintJobRepository(Protocol):
    def create(self, job: PrintJob) -> None: ...
    def update_status(self, job_id: str, status: PrintStatus, *, message: str = "", spool_job_id: int | None = None, error_code: str = "") -> None: ...
    def list_recent(self, limit: int = 500) -> list[PrintJob]: ...
    def correlation_exists(self, correlation_id: str) -> bool: ...


class IConfigurationService(Protocol):
    def load(self) -> dict[str, Any]: ...
    def save(self, config: dict[str, Any]) -> None: ...
    def set_password(self, config: dict[str, Any], password: str) -> None: ...
    def get_password(self, config: dict[str, Any]) -> str: ...
